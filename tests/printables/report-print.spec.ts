import { expect, test } from "@playwright/test";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";
import { readFile } from "node:fs/promises";

for (const format of ["A4", "Letter"] as const) for (const scenario of ["normal", "empty", "long", "quarterly", "selected"]) {
  test(`the ${scenario} report prints all rows without clipping on ${format}`, async ({ page }, testInfo) => {
    await page.goto(`/?scenario=${scenario}`);
    await expect(page.getByRole("article", { name: "Operational report" })).toBeVisible();
    await page.emulateMedia({ media: "print" });
    const sheet = page.locator(".report-sheet");
    const expectedRows = await sheet.locator("tbody tr").allTextContents();
    const source = await sheet.evaluate(node => {
      const clone = node.cloneNode(true) as HTMLElement;
      return clone.outerHTML;
    });
    const styles = await page.locator('style, link[rel="stylesheet"]').evaluateAll(nodes => nodes.map(node => node.outerHTML).join("\n"));
    await page.setContent(`<!doctype html><html><head>${styles}</head><body style="background: white">${source}</body></html>`);
    await page.evaluate(() => document.fonts.ready);
    const bytes = await page.pdf({ path: testInfo.outputPath(`${scenario}-${format}.pdf`), format, printBackground: true });
    const task = getDocument({ data: new Uint8Array(bytes), useSystemFonts: true });
    const pdf = await task.promise;
    const allText: string[] = [];
    const pageTexts: string[] = [];
    for (let index = 1; index <= pdf.numPages; index++) {
      const content = await (await pdf.getPage(index)).getTextContent();
      pageTexts.push(content.items.flatMap(item => "str" in item ? [item.str] : []).join(" "));
      for (const item of content.items) if ("str" in item && item.str.trim()) {
        expect(item.transform[4], `left edge of ${item.str}`).toBeGreaterThanOrEqual(35);
        expect(item.transform[4] + item.width, `right edge of ${item.str}`).toBeLessThanOrEqual(format === "A4" ? 560 : 577);
        allText.push(item.str);
      }
    }
    const normalized = allText.join(" ").replace(/\s+/g, " ");
    for (const row of expectedRows) {
      const service = row.match(/SERVICE \d+:/)?.[0];
      if (service) expect(normalized).toContain(service);
    }
    expect(normalized).toContain("Remarks");
    expect(normalized).toContain("Prepared by");
    expect(normalized).toContain("Generated by CiviCheck");
    expect((normalized.match(/\bTotal\b/g) ?? []).length).toBe(scenario === "selected" ? 0 : 2);
    if (scenario === "empty" || scenario === "selected") expect(pdf.numPages).toBe(1);
    expect(pageTexts.at(-1)).toContain("Remarks");
    expect(pageTexts.at(-1)).toContain("Prepared by");
    await task.destroy();
  });
}

test("Print copies only the report into a light document with its print styles", async ({ page }) => {
  await page.addInitScript(() => {
    window.print = () => document.documentElement.setAttribute("data-print-called", "true");
  });
  await page.goto("/?scenario=normal");
  await page.evaluate(() => document.documentElement.classList.add("dark"));
  await page.getByRole("button", { name: "Print report", exact: true }).click();
  const frame = page.frameLocator("iframe[data-print-frame]");
  await expect(frame.locator(".report-sheet")).toBeVisible();
  await expect(frame.getByRole("button")).toHaveCount(0);
  await expect(frame.locator("html")).toHaveAttribute("data-print-called", "true");
  await expect(frame.locator("html")).not.toHaveClass(/dark/);
  expect(await frame.locator("style, link[rel=stylesheet]").count()).toBeGreaterThan(0);
});

for (const label of ["Download acknowledgment", "Download verification form"]) {
  test(`${label} generates a complete PDF in the browser`, async ({ page }) => {
    await page.goto("/?scenario=pdf");
    const pending = page.waitForEvent("download");
    await page.getByRole("button", { name: label, exact: true }).click();
    const file = await pending;
    const bytes = await readFile((await file.path())!);
    expect(bytes.subarray(0, 5).toString()).toBe("%PDF-");
    const task = getDocument({ data: new Uint8Array(bytes), useSystemFonts: true });
    const pdf = await task.promise;
    const pages = [];
    for (let index = 1; index <= pdf.numPages; index++) {
      const content = await (await pdf.getPage(index)).getTextContent();
      pages.push(content.items.flatMap(item => "str" in item ? [item.str] : []).join(" "));
    }
    const text = pages.join(" ");
    expect(text).toContain("CCRO-2026-TEST0001");
    if (label === "Download verification form") {
      expect(text).toContain("INQUIRY-END");
      expect(text).toContain("NOTES-END");
    } else expect(text).toContain("DOCUMENT 31:");
    await task.destroy();
  });
}
